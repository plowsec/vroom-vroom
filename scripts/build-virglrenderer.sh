#!/bin/sh
# Build the virglrenderer vroom uses for 3D on macOS: virgl (OpenGL on
# Apple's OpenGL or ANGLE's Metal backend), Venus (Vulkan on MoltenVK) and
# Neptune (Direct3D 11 for Windows guests, on DXMT: scripts/build-dxmt.sh).
# Venus and Neptune run in its render server's workers, one process per
# guest context: vroom is the server and the worker (patch 0009).
#
# Base: UTM's macOS fork, pinned by hash, plus our patches in
# third_party/virglrenderer/. Meson fetches one subproject at a pinned
# commit (directx-native: Direct3D headers). It links a static libepoxy 1.5.10
# built with EGL and our patch (third_party/libepoxy/), which loads ANGLE
# from the directory virglrenderer is in. ANGLE itself comes from
# scripts/build-angle.sh; without it you get Venus only.
# Needs: meson ninja pkg-config molten-vk git (brew install meson ninja
# molten-vk), and Python's yaml (made in a venv under target/ if missing).
#
# Output: target/virglrenderer/lib/libvirglrenderer.1.dylib, also copied
# next to target/{debug,release}/vroom where the VMM looks first (with
# MoltenVK, and ANGLE's dylibs if built).
set -eu
cd "$(dirname "$0")/.."
ROOT=$(pwd)
URL=https://github.com/utmapp/virglrenderer/archive/451505ad0aa449290f2c0672da6877d57ee770e5.tar.gz
SHA=92a96c668a2ddc8a7e6846586554c4d45cba11cbf75557a39169ca58d71c81d2
EPOXY_URL=https://github.com/anholt/libepoxy/archive/refs/tags/1.5.10.tar.gz
EPOXY_SHA=a7ced37f4102b745ac86d6a70a9da399cc139ff168ba6b8002b4d8d43c900c15
WORK=$ROOT/target/virglrenderer-build
PREFIX=$ROOT/target/virglrenderer
log=$WORK/build.log

# Homebrew's formula env normally provides these.
MVK=$(brew --prefix molten-vk)
export LIBRARY_PATH="$MVK/lib${LIBRARY_PATH:+:$LIBRARY_PATH}"
export CPATH="$MVK/include${CPATH:+:$CPATH}"

mkdir -p "$WORK"
cd "$WORK"
: >"$log"

# The format tables are generated by a script that reads YAML.
if ! python3 -c 'import yaml' 2>/dev/null; then
  [ -x "$ROOT/target/pyenv/bin/python3" ] || python3 -m venv "$ROOT/target/pyenv"
  "$ROOT/target/pyenv/bin/python3" -c 'import yaml' 2>/dev/null || "$ROOT/target/pyenv/bin/pip" -q install pyyaml
  export PATH="$ROOT/target/pyenv/bin:$PATH"
fi

# libepoxy: static, no GLX/X11. EGL (for ANGLE) needs ANGLE's headers.
egl=no
if [ -d "$ROOT/target/angle/include/EGL" ]; then
  egl=yes
  export CPATH="$ROOT/target/angle/include:$CPATH"
fi
[ -f epoxy.tar.gz ] || curl -fsSL -o epoxy.tar.gz "$EPOXY_URL"
echo "$EPOXY_SHA  epoxy.tar.gz" | shasum -a 256 -c - >/dev/null
rm -rf epoxy && mkdir epoxy && tar xzf epoxy.tar.gz -C epoxy --strip-components 1
(cd epoxy && for p in "$ROOT"/third_party/libepoxy/*.patch; do patch -s -p1 < "$p"; done)
{ meson setup epoxy/build epoxy --prefix="$WORK/epoxy-prefix" --buildtype=release --default-library=static \
    -Degl=$egl -Dglx=no -Dx11=false -Dtests=false &&
  meson install -C epoxy/build; } >>"$log" 2>&1 || { tail -20 "$log"; exit 1; }
export PKG_CONFIG_PATH="$WORK/epoxy-prefix/lib/pkgconfig"

[ -f src.tar.gz ] && ! echo "$SHA  src.tar.gz" | shasum -a 256 -c - >/dev/null 2>&1 && rm src.tar.gz
[ -f src.tar.gz ] || curl -fsSL -o src.tar.gz "$URL"
echo "$SHA  src.tar.gz" | shasum -a 256 -c - >/dev/null
rm -rf src && mkdir src && tar xzf src.tar.gz -C src --strip-components 1
cd src
for p in "$ROOT"/third_party/virglrenderer/*.patch; do
  patch -s -p1 < "$p"
done
{ meson setup build --prefix="$PREFIX" --buildtype=release -Dvenus=true -Dneptune=true \
    -Drender-server-mode=process -Drender-server-worker=process -Dtests=false -Dvtest=false \
    -Dcheck-gl-errors=false &&
  meson compile -C build && meson install -C build; } >>"$log" 2>&1 || { tail -20 "$log"; exit 1; }
for d in debug release; do
  [ -d "$ROOT/target/$d" ] || continue
  # -f: Homebrew's MoltenVK is read-only, and so is our copy of it.
  cp -f "$PREFIX/lib/libvirglrenderer.1.dylib" "$ROOT/target/$d/"
  # Venus loads MoltenVK from virglrenderer's directory.
  cp -f "$MVK/lib/libMoltenVK.dylib" "$ROOT/target/$d/"
  for l in libEGL libGLESv2; do
    [ -f "$ROOT/target/angle/$l.dylib" ] && cp -f "$ROOT/target/angle/$l.dylib" "$ROOT/target/$d/"
  done
done
echo "built: $PREFIX/lib/libvirglrenderer.1.dylib"
